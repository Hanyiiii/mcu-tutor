// 检索知识库：按标签命中、问题匹配打分，返回 topN 条
export function searchKB(query, max = 3) {
  const q = (query || '').trim().toLowerCase()
  if (!q) return []
  const scored = []
  for (const item of KB) {
    let score = 0
    for (const tag of item.tags) {
      if (q.includes(tag.toLowerCase())) score += 5
      else if (tag.toLowerCase().includes(q) && q.length >= 2) score += 3
    }
    if (q.length >= 2 && item.q.toLowerCase().includes(q)) score += 4
    if (q.length >= 3 && item.a.toLowerCase().includes(q)) score += 1
    if (score > 0) scored.push({ item, score })
  }
  scored.sort((x, y) => y.score - x.score)
  return scored.slice(0, max).map((s) => s.item)
}

